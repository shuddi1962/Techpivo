// --- Presigned URL helpers (server-side only) ---

/** Generate a presigned PUT URL for direct browser-to-Blob uploads.
 *  Called from a server action / route handler; returns the URL + the
 *  public URL the file will be available at after upload.
 */
export interface PresignedUpload {
  uploadUrl: string
  publicUrl: string
  fields?: Record<string, string>
}

/** Placeholder — the actual public URL is generated by the API route
 *  (src/app/api/upload/route.ts) which holds the Vercel Blob token. This
 *  client-safe function only builds the public URL once the object key is
 *  known. Vercel Blob public URLs are served at images.techpivo.com. */
export function publicUrlForKey(key: string): string {
  return imageUrl(key)
}

// --- Responsive image hints ---

export interface ImageSize {
  width: number
  height: number
  quality?: number
  format?: "webp" | "avif"
}

/** Build an optimized image URL with transformation hints. Vercel Blob
 *  serves images at images.techpivo.com with CDN caching. These hints are
 *  advisory for downstream image optimization. */
export function optimizedImageUrl(path: string, size: ImageSize): string {
  const base = imageUrl(path)
  const params = new URLSearchParams()
  if (size.width) params.set("width", String(size.width))
  if (size.height) params.set("height", String(size.height))
  if (size.quality) params.set("quality", String(size.quality))
  if (size.format) params.set("format", size.format)
  const qs = params.toString()
  return qs ? `${base}?${qs}` : base
}

