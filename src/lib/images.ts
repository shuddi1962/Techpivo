// TechPivo image delivery — Vercel Blob via images.techpivo.com
//
// Public images (products, categories, banners, blogs) are served from
// https://images.techpivo.com/<path> with CDN-backed caching.
// Private images (avatars, draft uploads) use server-generated URLs — never
// expose the Blob token to the browser.
//
// Logical paths: /products/, /products/gallery/, /categories/, /banners/,
// /stores/, /brands/, /blog/, /promotions/, /avatars/, /uploads/

import { IMAGE_URL, IMAGE_DOMAIN } from "@/lib/constants"

// Public image URL — safe to use in <img src> on both techpivo.com and
// shop.techpivo.com. No secrets involved.
export function imageUrl(path: string): string {
  const normalized = path.startsWith("/") ? path.slice(1) : path
  return `${IMAGE_URL}/${normalized}`
}

// Product image URLs by logical path.
export const productImage = {
  main: (file: string) => imageUrl(`products/${file}`),
  gallery: (file: string) => imageUrl(`products/gallery/${file}`),
  thumbnail: (file: string, width: number) =>
    `${imageUrl(`products/${file}`)}?width=${width}&format=webp`,
}

